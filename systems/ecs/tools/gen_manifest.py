#!/usr/bin/env python3
"""Generate generated/manifest_data.h from the live-client manifest (manifest/*.json).

Input: manifest/ecs_{game,session,lobby}.json (Prometheus MCP `ecs_dump`) and
manifest/component_storage.json. Rerun after re-dumping: `tools/gen_manifest.py`.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, "../manifest")
OUT = os.path.join(HERE, "../generated/manifest_data.h")
ADMINS = ["game", "session", "lobby"]
DEFAULT_FNS = {"game+0x5a0c20", "game+0x5a45e0"}  # shared no-op callback / "return 0"
SLOTS = ["on_initialize", "pre_delete", "on_added", "on_created", "on_deleting", "on_removed", "on_tick"]


def rva(s):
    return int(s.split("+0x")[1], 16) if s and s.startswith("game+0x") else 0


def ids(lst):
    return [int(x, 16) for x in lst]


def main():
    dumps = {ea: json.load(open(os.path.join(MANIFEST, f"ecs_{ea}.json"))) for ea in ADMINS}
    storage = json.load(open(os.path.join(MANIFEST, "component_storage.json")))["untracked"]
    game = dumps["game"]
    count = game.get("component_id_count", game.get("max_component_id"))

    out = ["// Generated by tools/gen_manifest.py from manifest/*.json (live client dump). Do not edit.",
           "#pragma once", "#include \"ecs/types.h\"", "#include <cstdint>", "",
           "namespace ecs::manifest {", "",
           f"inline constexpr int kComponentIdCount = {count};", ""]

    comps = [c for c in game["components"] if "error" not in c and int(c["id"], 16) < count]
    for c in comps:
        deps = ids(c.get("dependencies", []))
        if deps:
            out.append(f"inline constexpr ComponentId kDeps_{c['id'][2:]}[] = {{{', '.join(hex(d) for d in deps)}}};")
    out += ["", "struct ComponentInfo {", "    ComponentId id;", "    bool has_creator;",
            "    uint32_t inline_size; // non-zero: inline-capable, never in the EA iteration lists",
            "    bool inline_entity_allocator; // [?] assumed = has a storage handler",
            "    const ComponentId* deps;", "    uint8_t dep_count;", "};", "",
            "inline constexpr ComponentInfo kComponents[] = {"]
    for c in comps:
        n = len(c.get("dependencies", []))
        size = c.get("untracked") or storage.get(c["id"], {}).get("value", 0)
        handler = (c.get("storage_handler") not in (None, "", "0x0")) or bool(storage.get(c["id"], {}).get("handler"))
        deps = f"kDeps_{c['id'][2:]}" if n else "nullptr"
        out.append(f"    {{{c['id']}, {'true' if c['creator_vtable'] else 'false'}, {size}, {'true' if handler else 'false'}, {deps}, {n}}},")
    out += ["};", ""]

    out += ["// Bits of SystemInfo::overrides: which callback slots differ from the shared defaults.",
            *[f"inline constexpr uint16_t kOverrides_{s} = 1 << {i};" for i, s in enumerate(SLOTS)], "",
            "struct SystemInfo {", "    uint32_t vtable_rva; // 0 = injected by Prometheus, not part of the game",
            "    const ComponentId* subs;", "    uint8_t sub_count;", "    uint16_t overrides;", "};", ""]
    for ea in ADMINS:
        systems = dumps[ea]["systems"]
        for s in systems:
            subs = ids(s.get("subscriptions", []))
            if subs:
                out.append(f"inline constexpr ComponentId kSubs_{ea}_{s['index']}[] = {{{', '.join(hex(x) for x in subs)}}};")
        out.append(f"inline constexpr SystemInfo kSystems_{ea}[] = {{")
        for s in systems:
            subs = s.get("subscriptions", [])
            ov = sum(1 << i for i, k in enumerate(SLOTS) if s.get("slots", {}).get(k) not in DEFAULT_FNS)
            arr = f"kSubs_{ea}_{s['index']}" if subs else "nullptr"
            out.append(f"    {{{hex(rva(s.get('vtable')))}, {arr}, {len(subs)}, {hex(ov)}}}, // [{s['index']}] {s.get('vtable')}")
        out += ["};", ""]

    cfl = json.load(open(os.path.join(MANIFEST, "command_frame_listeners.json")))
    out.append("// Command-frame listeners (EA+0xF0) in registration order, as owning-system vtable RVAs.")
    for ea in ADMINS:
        v = [int(x, 16) for x in cfl.get(ea, [])]
        out.append(f"inline constexpr uint32_t kCfListeners_{ea}[] = {{{', '.join(hex(x) for x in v) or '0'}}};")
    out += ["", "struct AdminInfo {", "    const char* name;", "    uint32_t vtable_rva;", "    const SystemInfo* systems;",
            "    int system_count;", "    const uint32_t* cf_listeners;", "    int cf_listener_count;", "};", "",
            "inline constexpr AdminInfo kAdmins[] = {"]
    for ea in ADMINS:
        out.append(f"    {{\"{ea}\", {hex(rva(dumps[ea]['vtable']))}, kSystems_{ea}, {len(dumps[ea]['systems'])}, "
                   f"kCfListeners_{ea}, {len(cfl.get(ea, []))}}},")
    out += ["};", "", "} // namespace ecs::manifest", ""]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(out))
    print("wrote", OUT, f"({len(comps)} component types)")


if __name__ == "__main__":
    main()
