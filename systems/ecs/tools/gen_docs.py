#!/usr/bin/env python3
"""Generate docs/ECS_Components.md and docs/ECS_Systems.md.

Facts come from the live manifest (manifest/components.json, manifest/systems.json: ids, sizes,
dependencies, subscriptions, EA membership, counts); interpretation from manifest/analysis/*.json
(Ghidra analysis per component / system). Edit the analysis files, not the generated docs.
"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
MAN = os.path.join(HERE, "../manifest")
DOCS = os.path.join(HERE, "../../../docs")
EAS = ["game", "session", "lobby"]


def load_analysis(prefix, key):
    out = {}
    for f in sorted(glob.glob(os.path.join(MAN, "analysis", f"{prefix}*.json"))):
        for e in json.load(open(f)):
            out[e[key].lower()] = e
    return out


def prom_name(s):
    """Prometheus's own list numbers systems ("System 23"); only the parenthesised part is a name."""
    n = s.get("prometheus_name", "")
    return n[n.find("(") + 1:n.rfind(")")] if "(" in n else ""


def cell(s):
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def main():
    comps = json.load(open(os.path.join(MAN, "components.json")))
    systems = json.load(open(os.path.join(MAN, "systems.json")))
    ca = load_analysis("components", "id")
    sa = load_analysis("systems", "vtable_rva")

    # system index per EA -> (vtable, name) for cross references
    by_ea_index = {}
    for s in systems:
        a = sa.get(s["vtable_rva"].lower(), {})
        for ea, i in s["eas"].items():
            by_ea_index[(ea, i)] = (s["vtable_rva"], a.get("name") or prom_name(s) or s["vtable_rva"])

    def cname(cid):
        c = next((c for c in comps["components"] if c["id"] == cid), None)
        if not c:
            return cid
        a = ca.get(cid.lower(), {})
        return (c.get("stu_name") or a.get("name") or "?").split(" / ")[0]

    # --- components --------------------------------------------------------------------------
    L = ["# ECS components", "",
         "Generated by `systems/ecs/tools/gen_docs.py` from the live manifest (`systems/ecs/manifest/`) and the",
         "Ghidra analysis in `systems/ecs/manifest/analysis/`. Mechanics: [ECS.md](ECS.md).", "",
         "- **STU**: the entity-definition component type that maps to this id (`FUN_7ff650ec7d70`, names from",
         "  OWLib KnownTypes). No STU name = added by engine code (dependency, specialised loader, runtime).",
         "- **size**: allocator slot size (bytes); **inline**: size when stored inline in a lightweight entity.",
         "- **count**: live instances after loading Temple of Anubis + controller spawn (game / session / lobby),",
         "  from the iteration lists: inline-capable types are never listed there and show 0.",
         "- **subscribers**: systems matched on this component (callbacks).", "",
         "| id | name | STU | size | inline | deps | count g/s/l | subscribers (game) | confidence |",
         "|---|---|---|---|---|---|---|---|---|"]
    for c in comps["components"]:
        a = ca.get(c["id"].lower(), {})
        name = c.get("stu_name") or a.get("name", "")
        subs = ", ".join(by_ea_index.get(("game", i), ("", str(i)))[1] for i in c.get("subscribers", {}).get("game", []) if isinstance(i, int))
        cnt = "/".join(str(c.get("counts", {}).get(ea, 0)) for ea in EAS)
        conf = "STU" if c.get("stu_name") else a.get("confidence", "")
        L.append(f"| `{c['id']}` | {cell(name)} | {'`'+c['stu_hash']+'`' if c.get('stu_hash') else ''} | {c.get('size','')} | "
                 f"{c.get('inline_size') or ''} | {', '.join(c.get('deps', []))} | {cnt} | {cell(subs)} | {conf} |")
    L += ["", "## Details", ""]
    for c in comps["components"]:
        a = ca.get(c["id"].lower(), {})
        name = c.get("stu_name") or a.get("name", "?")
        L.append(f"### `{c['id']}` {name}")
        if a.get("summary"):
            L.append(a["summary"])
        facts = []
        if a.get("added_by"): facts.append(f"added by: {a['added_by']}")
        if a.get("mirrored") is not None: facts.append(f"mirrored: {a['mirrored']}")
        if c.get("vtable"): facts.append(f"vtable `{c['vtable']}`")
        if c.get("def_count_game"): facts.append(f"{c['def_count_game']} entity definitions in the game EA")
        if a.get("server_relevance"): facts.append(f"server: {a['server_relevance']}")
        if facts:
            L.append("- " + "\n- ".join(facts))
        if a.get("fields"):
            L.append("- fields: " + "; ".join(f"`{k}` {v}" for k, v in a["fields"].items()))
        if a.get("evidence"):
            L.append(f"- evidence: {a['evidence']}")
        L.append("")
    un = comps.get("unmapped_stu", {})
    if un:
        L += ["## STU component types the client ignores", "",
              "These hashes are explicitly mapped to *no* runtime component by `FUN_7ff650ec7d70`: data the",
              "client doesn't instantiate (server-only or editor components). Relevant for a server.", ""]
        L += [f"- `{h}` {n or '(name unknown)'}" for h, n in un.items()]
    open(os.path.join(DOCS, "ECS_Components.md"), "w").write("\n".join(L) + "\n")

    # --- systems -------------------------------------------------------------------------------
    L = ["# ECS systems", "",
         "Generated by `systems/ecs/tools/gen_docs.py` from the live manifest and the Ghidra analysis in",
         "`systems/ecs/manifest/analysis/`. System names are stripped in the client; the names here are ours.",
         "Tick order = index within each EA (`game` / `session` / `lobby`). Mechanics: [ECS.md](ECS.md).", "",
         "| game | session | lobby | vtable | name | subscriptions | callbacks | confidence |",
         "|---|---|---|---|---|---|---|---|"]
    for s in sorted(systems, key=lambda s: (s["eas"].get("game", 99), s["eas"].get("session", 99), s["eas"].get("lobby", 99))):
        a = sa.get(s["vtable_rva"].lower(), {})
        name = a.get("name") or prom_name(s)
        subs = ", ".join(f"{x} {cname(x)}" for x in s.get("subscriptions", []))
        cbs = ", ".join(k.replace("on_", "") for k in s.get("slots", {}) if k not in ("on_initialize", "on_tick", "pre_delete"))
        idx = [str(s["eas"].get(ea, "")) for ea in EAS]
        L.append(f"| {idx[0]} | {idx[1]} | {idx[2]} | `{s['vtable_rva']}` | {cell(name)} | {cell(subs)} | {cbs} | {a.get('confidence', '')} |")
    L += ["", "## Details", ""]
    for s in sorted(systems, key=lambda s: (s["eas"].get("game", 99), s["eas"].get("session", 99), s["eas"].get("lobby", 99))):
        a = sa.get(s["vtable_rva"].lower(), {})
        name = a.get("name") or prom_name(s) or "?"
        where = ", ".join(f"{ea} #{i}" for ea, i in s["eas"].items())
        L.append(f"### {name} (`{s['vtable_rva']}`; {where})")
        if a.get("summary"): L.append(a["summary"])
        facts = []
        if a.get("tick"): facts.append(f"tick: {a['tick']}")
        if a.get("callbacks"): facts.append(f"callbacks: {a['callbacks']}")
        for k, label in (("components_iterated", "iterates"), ("components_read", "reads"), ("components_written", "writes")):
            if a.get(k): facts.append(f"{label}: " + ", ".join(f"{x} {cname(x)}" for x in a[k]))
        if a.get("interacts_with"): facts.append("interacts with: " + ", ".join(a["interacts_with"]))
        if a.get("fixed_step") is not None: facts.append(f"fixed-step (command frames): {a['fixed_step']}")
        if a.get("server_relevance"): facts.append(f"server: {a['server_relevance']}")
        slots = ", ".join(f"{k} `{v}`" for k, v in s.get("slots", {}).items())
        if slots: facts.append(f"slots: {slots}")
        if a.get("key_functions"):
            facts.append("functions: " + "; ".join(f"`{k}` {v}" for k, v in a["key_functions"].items()))
        if a.get("evidence"): facts.append(f"evidence: {a['evidence']}")
        if facts:
            L.append("- " + "\n- ".join(facts))
        L.append("")
    open(os.path.join(DOCS, "ECS_Systems.md"), "w").write("\n".join(L) + "\n")
    print("wrote docs/ECS_Components.md, docs/ECS_Systems.md",
          f"({len(ca)} analysed components, {len(sa)} analysed systems)")


if __name__ == "__main__":
    main()
