#!/usr/bin/env python3
"""Generate generated/type_table.h: every Statescript node / config-var STU type of the client (T014 catalogue,
systems/data/statescript/statescript_node_catalogue.json) with its kind, the STU type whose client class
implements it (the RTTI winner: exact type or nearest registered ancestor; 0 = no client class anywhere in the
chain = server-only logic), and for states the state-data facts of T052's spec
(systems/data/statescript/state_data_formats.json): has-update, local / remote format non-empty.
capabilities.cpp combines it with the runtime's own list of implemented types (docs/StatescriptNodes.md).
usage: tools/gen_type_table.py   (from anywhere)"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
data = os.path.join(here, "../../data/statescript")
cat = json.load(open(os.path.join(data, "statescript_node_catalogue.json")))
fmt = {t["hash"]: t for t in json.load(open(os.path.join(data, "state_data_formats.json")))["types"]}
KIND = {"Entry": "Entry", "Condition": "Condition", "Action": "Action", "Terminator": "Terminator",
        "State": "State", "ConfigVar": "ConfigVar", "Base": "Other"}
rows = []
for t in sorted(cat, key=lambda t: t["hash"]):
    impl = t["impl_from"] if t["runtime"] or t["impl_from"] != t["hash"] else None
    # A type with no client class inherits the one of impl_from; the STUStatescriptState / Action / … bases
    # themselves are "no class" for the capability view (they do nothing).
    base_names = ("STUStatescriptState", "STUStatescriptAction", "STUConfigVar", "STUStatescriptBase",
                  "STUStatescriptActionTerminator", "STUStatescriptCondition", "STUStatescriptEntry")
    if t.get("impl_from_name") in base_names and t["impl_from"] != t["hash"]:
        impl = None
    prio = max((r["prio"] for r in t["runtime"]), default=-1)
    f = fmt.get(t["hash"])
    hu = int(bool(f and f["has_update"]))
    loc = int(bool(f and f["local"]))
    rem = int(bool(f and f["remote"]))
    same = int(bool(f and f["local"] == f["remote"]))
    if t["kind"] == "State" and f is None:
        raise SystemExit(f"state type {t['hash']} missing from state_data_formats.json")
    rows.append(f"    {{0x{t['hash']}, TypeKind::{KIND[t['kind']]}, 0x{impl or '0'}, {prio}, {hu}, {loc}, {rem}, {same}, "
                f"{t['instances']}, 0x{t.get('parent') or '0'}}},  // {t.get('name') or '?'}")
out = os.path.join(here, "../generated/type_table.h")
with open(out, "w") as fo:
    fo.write("// Generated by tools/gen_type_table.py from systems/data/statescript/statescript_node_catalogue.json (T014)\n")
    fo.write("// and state_data_formats.json (T052). Do not edit.\n")
    fo.write("// {type, kind, client class type (0 = none), class priority layer (-1 = none), has update, local data,\n")
    fo.write("//  remote data, same local and remote format, instances in the 296 resident graphs, STU parent}\n#pragma once\n\n")
    fo.write("inline constexpr ClientType kClientTypes[] = {\n" + "\n".join(rows) + "\n};\n")
print(out, len(rows))
