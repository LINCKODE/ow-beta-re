#!/usr/bin/env python3
"""Enumerate the hero cosmetics of build 24919 offline (T026).

Reads every STUUnlock (type 0x0A5, GUIDs 0x025...), the 21 STUHero records, their
STUProgressionUnlocks (m_heroProgression, 0x0EA...) and each hero skin's STUSkinTheme
variants (m_skins -> m_skinThemes, 0x0A5...), with systems/content's content_dump and
systems/stu's stu_dump. Writes, next to this directory:

  unlocks.tsv       every unlock: class, name, owning heroes, SkinTheme slot
  hero_unlocks.tsv  per hero, per progression index: unlock, class, name
  hero_skins.tsv    per hero: skin, the 4 skin variants (m_slot, name)

and server/internal/lobbylogic/herounlocks_gen.go (the tables the lobby logic uses).
Run from anywhere; dumps are cached in $TMPDIR/hero_unlocks_cache.
"""
import json, os, subprocess, tempfile

R = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../.."))
OUT = os.path.join(R, "systems/data/lobby_scripts")
CD = [f"{R}/systems/content/build/content_dump", "--install", f"{R}/game/owbetaclient"]
CACHE = os.path.join(tempfile.gettempdir(), "hero_unlocks_cache")
os.makedirs(CACHE, exist_ok=True)

HEROES = [0x02E0000000000000 | h for h in
          (2, 3, 4, 5, 6, 7, 8, 9, 0xA, 0x15, 0x16, 0x20, 0x29, 0x40, 0x42, 0x65, 0x68, 0x6E, 0x79, 0x7A, 0xDD)]


def dump(guid):
    f = os.path.join(CACHE, f"{guid:016x}.json")
    if not os.path.exists(f):
        stud = os.path.join(CACHE, "x.stud")
        subprocess.run(CD + ["--read", hex(guid), stud], check=True, capture_output=True)
        js = subprocess.run([f"{R}/systems/stu/build/stu_dump", stud], check=True, capture_output=True, text=True).stdout
        open(f, "w").write(js)
    return json.load(open(f))["root"][0]


def g(v):
    return int(v["$guid"], 16)


strings = {}
for line in open(os.path.join(OUT, "strings_enUS.tsv"), encoding="utf-8"):
    k, _, v = line.rstrip("\n").partition("\t")
    strings[int(k, 16)] = v

listing = subprocess.run(CD + ["--list", "A5"], check=True, capture_output=True, text=True).stdout
unlocks = {}
for line in listing.splitlines():
    guid = int(line.split()[0], 16)
    unlocks[guid] = dump(guid)


def slot(u):
    f = unlocks[u]["value"]["$fields"]
    return int(f["0xbd085e06"], 16) if unlocks[u]["type"] == "STUUnlock_SkinTheme" else 0


rows, skins, owners, heroinfo = [], [], {}, []
for h in HEROES:
    hv = dump(h)["value"]["$fields"]
    name = strings.get(g(hv["0x0cd16baa"]), "")
    skin = g(hv["m_skins"][0])
    variants = []
    for t in dump(skin)["value"]["$fields"]["m_skinThemes"]:
        tv = dump(g(t))["value"]["$fields"]
        variants.append((int(tv["m_slot"], 16), g(t), strings.get(g(tv["0x0cd16baa"]), "")))
    variants.sort()
    skins += [(name, h, skin) + v for v in variants]
    own = []
    for idx, grp in enumerate(dump(g(hv["m_heroProgression"]))["value"]["$fields"]["m_unlocks"]):
        for u in grp["$fields"]["m_unlocks"]:
            u = g(u)
            f = unlocks[u]["value"]["$fields"]
            rows.append((name, h, idx, u, unlocks[u]["type"], strings.get(g(f["m_name"]), ""), slot(u)))
            owners.setdefault(u, []).append(name)
            own.append(u)
    heroinfo.append((h, name, skin, own, [v[2] for v in variants]))

with open(os.path.join(OUT, "hero_unlocks.tsv"), "w", encoding="utf-8") as o:
    o.write("hero\thero_guid\tprogression_index\tunlock\tclass\tname\tskin_theme_slot\n")
    for r in rows:
        o.write(f"{r[0]}\t{r[1]:#018x}\t{r[2]}\t{r[3]:#018x}\t{r[4]}\t{r[5]}\t{r[6] or ''}\n")
with open(os.path.join(OUT, "hero_skins.tsv"), "w", encoding="utf-8") as o:
    o.write("hero\thero_guid\tskin\tslot\tskin_theme\tname\n")
    for r in skins:
        o.write(f"{r[0]}\t{r[1]:#018x}\t{r[2]:#018x}\t{r[3]}\t{r[4]:#018x}\t{r[5]}\n")
with open(os.path.join(OUT, "unlocks.tsv"), "w", encoding="utf-8") as o:
    o.write("unlock\tclass\tname\theroes\tskin_theme_slot\n")
    for u in sorted(unlocks):
        f = unlocks[u]["value"]["$fields"]
        o.write(f"{u:#018x}\t{unlocks[u]['type']}\t{strings.get(g(f['m_name']), '')}\t"
                f"{','.join(owners.get(u, [])) if len(owners.get(u, [])) < len(HEROES) else 'all'}\t{slot(u) or ''}\n")

CLASS = {"STUUnlock_SkinTheme": "classSkinTheme", "STUUnlock_POTGAnimation": "classPOTG",
         "STUUnlock_SprayPaint": "classSpray", "STUUnlock_AvatarPortrait": "classAvatarPortrait",
         "STUUnlock_PortraitFrame": "classPortraitFrame"}
go = ["// Code generated by systems/data/lobby_scripts/tools/hero_unlocks.py; DO NOT EDIT.", "",
      "package lobbylogic", "",
      "// heroInfos: per hero (STUHero), its name, skin (m_skins[0]), unlocks in progression order",
      "// (m_heroProgression) and the names of the skin's 4 variants (STUSkinTheme m_slot 1-4).",
      "var heroInfos = []heroInfo{"]
for h, name, skin, own, vnames in heroinfo:
    go.append(f"\t{{{h:#018x}, {json.dumps(name, ensure_ascii=False)}, {skin:#018x}, []uint64{{"
              + ", ".join(f"{u:#018x}" for u in own) + "}, [4]string{"
              + ", ".join(json.dumps(v, ensure_ascii=False) for v in vnames) + "}},")
go += ["}", "", "// unlockInfos: every STUUnlock of 0.8 (class, m_name, SkinTheme slot 0xbd085e06).",
       "var unlockInfos = map[uint64]unlockInfo{"]
for u in sorted(unlocks):
    f = unlocks[u]["value"]["$fields"]
    go.append(f"\t{u:#018x}: {{{CLASS[unlocks[u]['type']]}, {json.dumps(strings.get(g(f['m_name']), ''), ensure_ascii=False)}, {slot(u)}}},")
go.append("}")
open(os.path.join(R, "server/internal/lobbylogic/herounlocks_gen.go"), "w", encoding="utf-8").write("\n".join(go) + "\n")
print(f"{len(unlocks)} unlocks, {len(rows)} hero unlock rows, {len(skins)} skin variants")
