package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"unicode"
)

// generate writes the Go codecs for every message of the catalogue: one struct per
// message and per anonymous nested struct, Encode/Decode, the protocol table and
// the ID -> message registry. The wire primitives (put*/get*, JamID, ...) are
// hand-written in the jam package (codec.go).
func generate(c *Catalogue, pkg string) ([]byte, error) {
	g := &gen{c: c}
	g.p("// Code generated by jamgen from systems/data/jam/catalogue.json; DO NOT EDIT.\n")
	g.p("\npackage %s\n\nimport \"owserver/inst/bits\"\n", pkg)

	// Protocol table.
	g.p("\n// protocols is every protocol the client registers, sorted by name (Negotiation first).\nvar protocols = []Protocol{\n")
	for _, p := range c.Protocols {
		ch := -1
		if p.InstanceChannel != nil {
			ch = *p.InstanceChannel
		}
		g.p("\t{Name: %q, CRC: 0x%08x, Base: %d, Max: %d, Direction: %q, Transport: %q, ServerType: %d, InstanceChannel: %d},\n",
			p.Name, uint32(p.CRC), p.Base, p.Max, p.Direction, p.Transport, p.ServerType, ch)
	}
	g.p("}\n")

	// IDs.
	g.p("\n// Message IDs.\nconst (\n")
	for _, p := range c.Protocols {
		for _, m := range p.Messages {
			g.p("\tID%s uint16 = %d\n", m.GoName(p), m.ID)
		}
	}
	g.p(")\n")

	// Registry.
	g.p("\n// New returns an empty message of the given ID.\nfunc New(id uint16) (Message, bool) {\n\tswitch id {\n")
	for _, p := range c.Protocols {
		for _, m := range p.Messages {
			g.p("\tcase %d:\n\t\treturn new(%s), true\n", m.ID, m.GoName(p))
		}
	}
	g.p("\t}\n\treturn nil, false\n}\n")

	g.p("\n// messageNames maps IDs to Go type names.\nvar messageNames = map[uint16]string{\n")
	for _, p := range c.Protocols {
		for _, m := range p.Messages {
			g.p("\t%d: %q,\n", m.ID, m.GoName(p))
		}
	}
	g.p("}\n")

	for _, t := range c.Types {
		if builtinTypes[t.Name] {
			continue
		}
		g.p("\n// %s is a shared struct (catalogue type).\n", t.Name)
		if t.Notes != "" {
			g.comment(t.Notes)
		}
		if err := g.structType(t.Name, t.Fields); err != nil {
			return nil, err
		}
		if err := g.codec(t.Name, t.Fields, false); err != nil {
			return nil, err
		}
		if err := g.flush(); err != nil {
			return nil, err
		}
	}
	for _, p := range c.Protocols {
		for _, m := range p.Messages {
			if err := g.message(p, m); err != nil {
				return nil, fmt.Errorf("%s %d: %w", p.Name, m.ID, err)
			}
		}
	}
	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("gofmt: %w", err)
	}
	return src, nil
}

type gen struct {
	c   *Catalogue
	buf bytes.Buffer
	// nested struct types to emit after the current message
	pending []nestedType
}

type nestedType struct {
	name   string
	fields []*Field
	where  string
}

func (g *gen) p(f string, a ...any) { fmt.Fprintf(&g.buf, f, a...) }

func (g *gen) message(p *Protocol, m *Message) error {
	name := m.GoName(p)
	g.p("\n// %s is %s %d (index %d", name, p.Name, m.ID, m.ID-p.Base)
	if m.Handler != "" {
		g.p(", client %s", m.Handler)
	}
	g.p(").")
	if m.Label != "" {
		g.p(" %s.", strings.TrimSuffix(m.Label, "."))
	}
	g.p("\n")
	if m.Notes != "" {
		g.comment(m.Notes)
	}
	if err := g.structType(name, m.Fields); err != nil {
		return err
	}
	g.p("\nfunc (*%s) ID() uint16 { return %d }\n", name, m.ID)
	if err := g.codec(name, m.Fields, true); err != nil {
		return err
	}
	return g.flush()
}

// flush emits the nested struct types queued while emitting a type.
func (g *gen) flush() error {
	for len(g.pending) > 0 {
		n := g.pending[0]
		g.pending = g.pending[1:]
		g.p("\n// %s is a struct in %s.\n", n.name, n.where)
		if err := g.structType(n.name, n.fields); err != nil {
			return err
		}
		if err := g.codec(n.name, n.fields, false); err != nil {
			return err
		}
	}
	return nil
}

func (g *gen) comment(s string) {
	for _, line := range wrap(s, 100) {
		g.p("// %s\n", line)
	}
}

func wrap(s string, n int) []string {
	var out []string
	line := ""
	for _, w := range strings.Fields(s) {
		if line != "" && len(line)+1+len(w) > n {
			out = append(out, line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += w
	}
	if line != "" {
		out = append(out, line)
	}
	return out
}

func (g *gen) structType(name string, fs []*Field) error {
	if len(fs) == 0 {
		g.p("type %s struct{}\n", name)
		return nil
	}
	g.p("type %s struct {\n", name)
	names := fieldNames(fs)
	for i, f := range fs {
		t, err := g.goType(name, names[i], f)
		if err != nil {
			return err
		}
		c := ""
		if f.Notes != "" {
			c = " // " + f.Notes
		}
		g.p("\t%s %s%s\n", names[i], t, c)
	}
	g.p("}\n")
	return nil
}

// goType returns the Go type of a field (queueing a nested struct type).
func (g *gen) goType(owner, fname string, f *Field) (string, error) {
	elem, err := g.elemType(owner, fname, f)
	if err != nil {
		return "", err
	}
	switch f.Array {
	case "":
		return elem, nil
	case "[]":
		return "[]" + elem, nil
	}
	return "[" + f.Array + "]" + elem, nil
}

func (g *gen) elemType(owner, fname string, f *Field) (string, error) {
	switch f.Type {
	case "bool":
		return "bool", nil
	case "char":
		return "byte", nil
	case "u8", "i8", "u16", "i16", "u32", "i32", "u64", "i64":
		return map[byte]string{'u': "uint", 'i': "int"}[f.Type[0]] + f.Type[1:], nil
	case "f32":
		return "float32", nil
	case "f64":
		return "float64", nil
	case "str":
		return "string", nil
	case "blob":
		return fmt.Sprintf("[%d]byte", f.Size), nil
	case "bytes":
		return "[]byte", nil
	case "tid":
		return "TaggedID", nil
	case "struct":
		n := owner + fname
		nestedName[f] = n
		g.pending = append(g.pending, nestedType{name: n, fields: f.Fields, where: owner})
		return n, nil
	}
	if t := g.c.typeByName(f.Type); t != nil {
		if t.Go != "" {
			return t.Go, nil
		}
		return t.Name, nil
	}
	return "", fmt.Errorf("unknown type %q", f.Type)
}

// builtinTypes are the named types hand-written in the jam package (codec.go).
var builtinTypes = map[string]bool{"JamID": true, "EntityID": true, "Vec3": true, "Vec4": true}

// isStruct reports whether a field is encoded by a generated encode/decode method.
func (g *gen) isStruct(f *Field) bool {
	return f.Type == "struct" || (g.c.typeByName(f.Type) != nil && !builtinTypes[f.Type])
}

// primitive returns the put/get suffix of a non-struct element type.
func (g *gen) primitive(f *Field) string {
	switch f.Type {
	case "bool":
		return "Bool"
	case "char":
		return "Char"
	case "str":
		return "Str"
	case "bytes":
		return "Bytes"
	case "tid":
		return "TaggedID"
	case "blob", "struct":
		return ""
	}
	if t := g.c.typeByName(f.Type); t != nil {
		if t.Go != "" {
			return t.Go
		}
		return t.Name
	}
	return strings.ToUpper(f.Type[:1]) + f.Type[1:]
}

func (g *gen) codec(name string, fs []*Field, isMsg bool) error {
	recv := "m"
	names := fieldNames(fs)
	if isMsg {
		g.p("\nfunc (%s *%s) Encode(w *bits.Writer) {\n", recv, name)
	} else {
		g.p("\nfunc (%s *%s) encode(w *bits.Writer) {\n", recv, name)
	}
	for i, f := range fs {
		g.encodeField(recv+"."+names[i], f, 1)
	}
	g.p("}\n")

	if isMsg {
		g.p("\nfunc (%s *%s) Decode(r *bits.Reader) error {\n\td := decoder{r: r}\n\t%s.decode(&d)\n\treturn d.err()\n}\n", recv, name, recv)
	}
	g.p("\nfunc (%s *%s) decode(d *decoder) {\n", recv, name)
	for i, f := range fs {
		g.decodeField(recv+"."+names[i], f, 1)
	}
	g.p("}\n")
	return nil
}

func (g *gen) encodeField(v string, f *Field, depth int) {
	ind := strings.Repeat("\t", depth)
	if f.Array != "" {
		idx := "i" + strconv.Itoa(depth)
		if f.Array == "[]" {
			g.p("%sputCount(w, len(%s))\n", ind, v)
		}
		g.p("%sfor %s := range %s {\n", ind, idx, v)
		e := *f
		e.Array = ""
		g.encodeField(v+"["+idx+"]", &e, depth+1)
		g.p("%s}\n", ind)
		return
	}
	switch {
	case g.isStruct(f):
		g.p("%s%s.encode(w)\n", ind, v)
		return
	}
	switch f.Type {
	case "blob":
		g.p("%sw.Bytes(%s[:])\n", ind, v)
	case "bool":
		g.p("%sw.Bool(%s)\n", ind, v)
	default:
		g.p("%sput%s(w, %s)\n", ind, g.primitive(f), v)
	}
}

func (g *gen) decodeField(v string, f *Field, depth int) {
	ind := strings.Repeat("\t", depth)
	if f.Array != "" {
		idx := "i" + strconv.Itoa(depth)
		if f.Array == "[]" {
			t := nestedName[f]
			if f.Type != "struct" {
				t, _ = g.elemType("", "", f)
			}
			g.p("%s%s = make([]%s, d.count(%d))\n", ind, v, t, minBits(g.c, f))
		}
		g.p("%sfor %s := range %s {\n", ind, idx, v)
		e := *f
		e.Array = ""
		g.decodeField(v+"["+idx+"]", &e, depth+1)
		g.p("%s}\n", ind)
		return
	}
	switch {
	case g.isStruct(f):
		g.p("%s%s.decode(d)\n", ind, v)
		return
	}
	switch f.Type {
	case "blob":
		g.p("%sd.blob(%s[:])\n", ind, v)
	case "bool":
		g.p("%s%s = d.r.Bool()\n", ind, v)
	default:
		g.p("%s%s = d.get%s()\n", ind, v, g.primitive(f))
	}
}

// nestedName records the Go type name given to each nested struct field (by
// elemType), so decodeField can allocate slices of it.
var nestedName = map[*Field]string{}

// minBits is the smallest encoding of one array element, used to reject bogus
// counts before allocating.
func minBits(c *Catalogue, f *Field) int {
	switch f.Type {
	case "bool":
		return 1
	case "struct":
		n := 0
		for _, s := range f.Fields {
			n += fieldMinBits(c, s)
		}
		return n
	}
	return fieldMinBits(c, &Field{Type: f.Type, Size: f.Size})
}

func fieldMinBits(c *Catalogue, f *Field) int {
	if f.Array == "[]" {
		return 32
	}
	n := 1
	if f.Array != "" {
		n, _ = strconv.Atoi(f.Array)
	}
	switch f.Type {
	case "bool":
		return n
	case "str":
		return 8 * n
	case "bytes":
		return 32 * n
	case "tid":
		return 16 * n
	case "blob":
		return 8 * f.Size * n
	case "struct":
		return minBits(c, f) * n
	}
	if t := c.typeByName(f.Type); t != nil {
		s := 0
		for _, x := range t.Fields {
			s += fieldMinBits(c, x)
		}
		return s * n
	}
	return 8 * scalarSize(f.Type) * n
}

// fieldNames returns the Go field names: the catalogue names in CamelCase, F<i>
// for unnamed fields.
func fieldNames(fs []*Field) []string {
	out := make([]string, len(fs))
	used := map[string]bool{}
	for i, f := range fs {
		n := goIdent(f.Name)
		if n == "" || used[n] {
			n = fmt.Sprintf("F%d", i)
		}
		used[n] = true
		out[i] = n
	}
	return out
}

func goIdent(s string) string {
	s = strings.TrimPrefix(s, "m_")
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' || r == ' ' || r == '-' {
			up = true
			continue
		}
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	out := b.String()
	if out != "" && unicode.IsDigit(rune(out[0])) {
		out = "F" + out
	}
	return out
}
