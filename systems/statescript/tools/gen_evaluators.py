#!/usr/bin/env python3
"""Generate generated/literal_config_vars.h from T038's catalogue (systems/data/statescript/configvar_catalogue.json):
the config-var types whose value is a literal of the STU object (GUID reference, enum/int field, constants,
vectors, colour, string). config_vars.cpp registers a generic evaluator for each.
usage: tools/gen_evaluators.py   (from systems/statescript)"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
cat = json.load(open(os.path.join(here, "../../data/statescript/configvar_catalogue.json")))
KINDS = [  # (catalogue 'computes' prefix, kind)
    ("the GUID of the referenced asset", "Guid"),
    ("the enum / int field at cv+0x10", "IntField"),
    ("constant false", "False"),
    ("Constant true", "True"),
    ("Constant 20.0", "Twenty"),
    ("Returns the literal byte m_value", "Byte"),
    ("Outputs m_value", "Float"),
    ("Literal colour", "Color"),
    ("Copies the literal m_value (STU string", "String"),
    ("Literal: copies the three floats", "Vec3"),
    ("Literal: copies two floats", "Vec2"),
]
rows = []
for t in sorted(cat, key=lambda t: t["hash"]):
    if t.get("reads") != "literal":
        continue
    kind = next((k for p, k in KINDS if t["computes"].startswith(p)), None)
    if kind is None:
        raise SystemExit(f"unclassified literal type {t['hash']}: {t['computes']}")
    rows.append(f"    {{0x{t['hash']}, LiteralKind::{kind}}},  // {t.get('name') or '?'}")
out = os.path.join(here, "../generated/literal_config_vars.h")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_evaluators.py from systems/data/statescript/configvar_catalogue.json (T038).\n")
    f.write("// Config-var types whose value is a literal of their STU object. Do not edit.\n#pragma once\n\n")
    f.write("inline constexpr struct { uint32_t type; LiteralKind kind; } kLiteralConfigVars[] = {\n")
    f.write("\n".join(rows) + "\n};\n")
print(out, len(rows))
