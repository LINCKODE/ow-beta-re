#!/usr/bin/env python3
"""Generate generated/registry_data.h from the client's STU type registry dump
(systems/data/client_stu_registry.json) plus OWLib's name tables (names/*.csv, the
0.8-era "DataPreHashChange" set) and the game directory's hashlibrary.json if present.

Usage: gen_registry.py [--registry PATH] [--out PATH]
The generated header is checked in; rerun after changing the inputs.
"""
import argparse
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)  # systems/stu

# Primitive element hashes (CRC32 of the type name): names from Prometheus STU.h and OWLib
# RegisteredSTUTypes (joined by field hash, see report T006). Sizes measured in the client.
PRIMITIVES = {
    0x3b9327d2: ("u8", 1), 0x6dc98054: ("s8", 1),
    0xa49ce182: ("u16", 2), 0xa0119d30: ("s16", 2),
    0x91c74719: ("u32", 4), 0x954a3bab: ("s32", 4),
    0x05d31669: ("u64", 8), 0x015e6adb: ("s64", 8),
    0x8fa75a30: ("f32", 4), 0x1bb30b40: ("f64", 8),
    0x0c525b48: ("teEntityID", 4),
    0xf6ec8926: ("teVec2", 8), 0x81ebb9b0: ("teVec3", 16), 0x2357e676: ("teVec3A", 16),
    0x1f8f2c13: ("teVec4", 16), 0xda9494c8: ("teQuat", 16),
    0x525114ab: ("teColorRGB", 12), 0xa9e19537: ("teColorRGBA", 16),
    0xe1b9e763: ("teStructuredDataDateAndTime", 8),
    0x20b3d5a9: ("DBID", 16), 0x809899f3: ("teUUID", 16),
    0xbbca304b: ("teString", 16), 0x6fb9880b: ("teMtx43A", 64),
}


def read_csv_names(path):
    out = {}
    if not os.path.exists(path):
        return out
    with open(path, newline="") as f:
        for row in csv.reader(f):
            if len(row) < 2:
                continue
            try:
                out[int(row[0].strip(), 16)] = row[1].strip()
            except ValueError:
                pass
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", default=os.path.join(ROOT, "..", "data", "client_stu_registry.json"))
    ap.add_argument("--names", default=os.path.join(ROOT, "names"))
    ap.add_argument("--hashlibrary", default=os.path.join(ROOT, "..", "..", "game", "owbetaclient", "hashlibrary.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "generated", "registry_data.h"))
    a = ap.parse_args()

    reg = json.load(open(a.registry))
    names = {}
    # lowest priority first
    if os.path.exists(a.hashlibrary):
        try:
            for k, v in json.load(open(a.hashlibrary)).get("db", {}).items():
                names[int(k, 16)] = v
        except (ValueError, json.JSONDecodeError):
            pass
    for fn in ("KnownEnums.csv", "KnownFields.csv", "KnownTypes.csv"):
        names.update(read_csv_names(os.path.join(a.names, fn)))
    for h, (n, _) in PRIMITIVES.items():
        names[h] = n

    order = sorted(reg.keys(), key=lambda h: int(h, 16))
    fields = []  # flat field table
    types = []
    for h in order:
        t = reg[h]
        first = len(fields)
        for f in t["fields"]:
            elem = int(f["elem"], 16) if f.get("elem") else 0
            fields.append((int(f["hash"], 16), f["offset"], f["ctype"], elem, f["flags"]))
        types.append((int(h, 16), int(t["parent"], 16) if t["parent"] else 0, t["size"],
                      int(t["layout_crc"], 16), t["flag58"], first, len(t["fields"])))

    used = set(x[0] for x in types) | set(f[0] for f in fields) | set(f[3] for f in fields) | set(PRIMITIVES)
    name_rows = sorted((h, n) for h, n in names.items() if h in used)

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    with open(a.out, "w") as o:
        o.write("// Generated by tools/gen_registry.py from systems/data/client_stu_registry.json\n")
        o.write("// and OWLib name tables. Do not edit.\n#pragma once\n#include <cstdint>\n#include <cstddef>\n\n")
        o.write("namespace stu::generated {\n\n")
        o.write("struct FieldRow { uint32_t hash; uint32_t offset; uint8_t kind; uint32_t elem; uint32_t flags; };\n")
        o.write("struct TypeRow { uint32_t hash; uint32_t parent; uint32_t size; uint64_t layout_crc; uint32_t flag58; uint32_t first_field; uint32_t field_count; };\n")
        o.write("struct NameRow { uint32_t hash; const char* name; };\n")
        o.write("struct PrimitiveRow { uint32_t hash; uint32_t size; };\n\n")
        o.write("inline constexpr FieldRow kFields[] = {\n")
        for f in fields:
            o.write("    {0x%08x, 0x%x, %d, 0x%08x, %d},\n" % f)
        o.write("};\ninline constexpr size_t kFieldCount = sizeof(kFields) / sizeof(kFields[0]);\n\n")
        o.write("inline constexpr TypeRow kTypes[] = {  // sorted by hash\n")
        for t in types:
            o.write("    {0x%08x, 0x%08x, 0x%x, 0x%016xull, %d, %d, %d},\n" % t)
        o.write("};\ninline constexpr size_t kTypeCount = sizeof(kTypes) / sizeof(kTypes[0]);\n\n")
        o.write("inline constexpr NameRow kNames[] = {  // sorted by hash\n")
        for h, n in name_rows:
            o.write('    {0x%08x, "%s"},\n' % (h, esc(n)))
        o.write("};\ninline constexpr size_t kNameCount = sizeof(kNames) / sizeof(kNames[0]);\n\n")
        o.write("inline constexpr PrimitiveRow kPrimitives[] = {  // sorted by hash\n")
        for h in sorted(PRIMITIVES):
            o.write("    {0x%08x, %d},\n" % (h, PRIMITIVES[h][1]))
        o.write("};\ninline constexpr size_t kPrimitiveCount = sizeof(kPrimitives) / sizeof(kPrimitives[0]);\n\n")
        o.write("} // namespace stu::generated\n")
    print("types %d fields %d names %d -> %s" % (len(types), len(fields), len(name_rows), a.out), file=sys.stderr)


if __name__ == "__main__":
    main()
